import math


def solve_quadratic():
    print("--- Розв'язання квадратного рівняння ax^2 + bx + c = 0 ---")

    try:
        # Введення коефіцієнтів користувачем з терміналу
        a = float(input("Введіть коефіцієнт a: "))
        b = float(input("Введіть коефіцієнт b: "))
        c = float(input("Введіть коефіцієнт c: "))
    except ValueError:
        print("Помилка: будь ласка, вводьте лише числа!")
        return

    # Перевірка на ділення на 0 (якщо a == 0, це лінійне рівняння bx + c = 0)
    if a == 0:
        if b != 0:
            x = -c / b
            print(f"Коефіцієнт a = 0. Це лінійне рівняння. Його корінь: x = {x}")
        else:
            if c == 0:
                print("Коефіцієнти a, b та c дорівнюють 0. Рівняння має безліч розв'язків.")
            else:
                print("Рівняння не має змісту (0 не дорівнює c).")
        return

    # Обчислення дискримінанту за допомогою math.pow()
    d = math.pow(b, 2) - 4 * a * c
    print(f"Дискримінант (D) = {d}")

    if d > 0:
        # Два дійсних корені
        x1 = (-b + math.sqrt(d)) / (2 * a)
        x2 = (-b - math.sqrt(d)) / (2 * a)
        print(f"Рівняння має два корені: x1 = {x1}, x2 = {x2}")
    elif d == 0:
        # Один корінь
        x = -b / (2 * a)
        print(f"Рівняння має один корінь: x = {x}")
    else:
        # Якщо D < 0
        print("Рівняння не має дійсних коренів (D < 0)")


# Запуск функції
solve_quadratic()
